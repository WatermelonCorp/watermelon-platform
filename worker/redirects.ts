/** Showcases were removed (#222); templates are the closest replacement. */
export function redirectFor(pathname: string): string | undefined {
  if (movedPaths[pathname]) return movedPaths[pathname];
  if (pathname === '/showcases' || pathname.startsWith('/showcase/')) return '/templates';
  return undefined;
}
